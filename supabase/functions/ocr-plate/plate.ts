export const PROVINCES = ["กรุงเทพมหานคร","กระบี่","กาญจนบุรี","กาฬสินธุ์","กำแพงเพชร","ขอนแก่น","จันทบุรี","ฉะเชิงเทรา","ชลบุรี","ชัยนาท","ชัยภูมิ","ชุมพร","เชียงราย","เชียงใหม่","ตรัง","ตราด","ตาก","นครนายก","นครปฐม","นครพนม","นครราชสีมา","นครศรีธรรมราช","นครสวรรค์","นนทบุรี","นราธิวาส","น่าน","บึงกาฬ","บุรีรัมย์","ปทุมธานี","ประจวบคีรีขันธ์","ปราจีนบุรี","ปัตตานี","พระนครศรีอยุธยา","พะเยา","พังงา","พัทลุง","พิจิตร","พิษณุโลก","เพชรบุรี","เพชรบูรณ์","แพร่","ภูเก็ต","มหาสารคาม","มุกดาหาร","แม่ฮ่องสอน","ยโสธร","ยะลา","ร้อยเอ็ด","ระนอง","ระยอง","ราชบุรี","ลพบุรี","ลำปาง","ลำพูน","เลย","ศรีสะเกษ","สกลนคร","สงขลา","สตูล","สมุทรปราการ","สมุทรสงคราม","สมุทรสาคร","สระแก้ว","สระบุรี","สิงห์บุรี","สุโขทัย","สุพรรณบุรี","สุราษฎร์ธานี","สุรินทร์","หนองคาย","หนองบัวลำภู","อ่างทอง","อำนาจเจริญ","อุดรธานี","อุตรดิตถ์","อุทัยธานี","อุบลราชธานี"];

const THAI_DIGITS = "๐๑๒๓๔๕๖๗๘๙";

/** แปลงเป็นรูปแบบมาตรฐาน: "2ฒพ 1630" หรือ "70-1234" (เลขไทย→อารบิก, ตัดวรรณยุกต์/สระ/ช่องว่างเกิน) */
export function normalizePlate(raw: unknown): string {
  let s = String(raw ?? "").trim();
  s = s.replace(/[๐-๙]/g, (d) => String(THAI_DIGITS.indexOf(d)));
  s = s.replace(/[–—‑−]/g, "-");
  s = s.replace(/[^0-9ก-ฮ\-\s]/g, ""); // ป้ายมีเฉพาะพยัญชนะ ตัวเลข และขีด
  const t = s.replace(/\s+/g, ""); // รูปแบบป้ายตายตัว จึงตัดช่องว่างทั้งหมดแล้วจัดรูปใหม่
  const a = t.match(/^(\d{0,2})([ก-ฮ]{1,3})-?(\d{1,4})$/);
  if (a) return `${a[1]}${a[2]} ${a[3]}`;
  const b = t.match(/^(\d{2})-?(\d{4})$/);
  if (b) return `${b[1]}-${b[2]}`;
  return s.replace(/\s+/g, " ").trim();
}

/** รูปแบบป้ายที่พบบ่อย: 1กก 1234 · กก 1234 · 1กข 123 · 70-1234 */
export function validPlate(p: string): boolean {
  return /^\d{0,2}[ก-ฮ]{1,3} \d{1,4}$/.test(p) || /^\d{2}-\d{4}$/.test(p);
}

/** ตัวเทียบเพื่อดูว่าสองผลอ่านเป็น "ป้ายเดียวกัน" ไหม */
export const plateKey = (p: string) => p.replace(/[\s-]/g, "");

function lev(a: string, b: string): number {
  const dp = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) dp[0][j] = j;
  for (let i = 1; i <= a.length; i++)
    for (let j = 1; j <= b.length; j++)
      dp[i][j] = Math.min(dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return dp[a.length][b.length];
}

/** จับชื่อจังหวัดที่อ่านได้ให้ตรงรายชื่อมาตรฐาน (คืน null ถ้าไม่แน่ใจ) */
export function matchProvince(raw: unknown): string | null {
  let s = String(raw ?? "").trim().replace(/^(จังหวัด|จ\.)\s*/, "").replace(/\s+/g, "");
  if (!s) return null;
  if (/^(กทม\.?|กรุงเทพ|กรุงเทพฯ|bangkok)$/i.test(s)) return "กรุงเทพมหานคร";
  if (PROVINCES.includes(s)) return s;
  let best: string | null = null, bd = 99;
  for (const p of PROVINCES) { const d = lev(s, p); if (d < bd) { bd = d; best = p; } }
  return best && bd <= (s.length >= 6 ? 2 : 1) ? best : null;
}
